export interface Board {
  title: string;
  kind: Round['kind'];
  /** نص يظهر فوق الخانات */
  direction?: string;
  items: DndItem[];
  slots: DndSlot[];
}

/** يبني لوح الجولة: بطاقات مخلوطة + خانات مع الإجابة الصحيحة لكل خانة */
export function buildBoard(round: Round, rnd: () => number = Math.random): Board {
  if (round.kind === 'match') {
    const items = round.pairs.map((p, i) => ({ id: `t${i}`, label: p.term }));
    const slots = round.pairs.map((p, i) => ({ id: `s${i}`, label: p.def, answerId: `t${i}` }));
    return { title: round.title, kind: 'match', items: shuffle(items, rnd), slots };
  }
  const items = round.sequence.map((label, i) => ({ id: `i${i}`, label }));
  const slots = round.sequence.map((_, i) => ({ id: `s${i}`, label: String(i + 1), answerId: `i${i}` }));
  return { title: round.title, kind: 'order', direction: round.direction, items: shuffle(items, rnd), slots };
}

/** جلسة كاملة: كل جولات المستوى بترتيب عشوائي */
export function buildRounds(difficulty: Difficulty, rnd: () => number = Math.random): Round[] {
  return shuffle(DRAG_BANK[difficulty], rnd);
}
