/** جولة مطابقة: اسحبوا كل مصطلح إلى تعريفه */
export interface MatchRound {
  kind: 'match';
  title: string;
  pairs: { term: string; def: string }[];
}
/** جولة ترتيب: sequence مكتوبة بالترتيب الصحيح */
export interface OrderRound {
  kind: 'order';
  title: string;
  /** يظهر فوق الخانات: مثل «من الأقرب إلى الأبعد» */
  direction: string;
  sequence: string[];
}
export type Round = MatchRound | OrderRound;

