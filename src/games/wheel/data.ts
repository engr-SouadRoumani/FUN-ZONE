/** سؤال جاهز للعرض بعد خلط الخيارات */
export interface DrawnQuestion {
  id: string;
  cat: Category;
  q: string;
  options: string[];
  answer: number;
  explain: string;
}

/**
 * يسحب سؤالاً غير مستخدم. إن لم يبقَ سؤال من الفئة المطلوبة يُسحب من أي فئة.
 * الخيارات تُخلط حتى لا تتكرر مواضع الإجابة الصحيحة.
 */
export function drawQuestion(bank: WheelQ[], used: Set<string>, wanted?: Category, rnd: () => number = Math.random): DrawnQuestion | null {
  const free = bank.filter(x => !used.has(x.id));
  if (!free.length) return null;
  const pool = (wanted && free.filter(x => x.cat === wanted)) || [];
  const src = pool.length ? pool : free;
  const pick = src[Math.floor(rnd() * src.length)];
  const order = shuffle(pick.options.map((_, i) => i), rnd);
  return {
    id: pick.id,
    cat: pick.cat,
    q: isolateMath(pick.q),
    options: order.map(i => isolateMath(pick.options[i])),
    answer: order.indexOf(pick.answer),
    explain: isolateMath(pick.explain),
  };
}
